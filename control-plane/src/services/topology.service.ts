import { Peer, DynamicTopology, PeerMeshEntry } from '../models/types.js';
import { peerStore } from '../models/store.js';
import { NETWORK_CIDR, NETWORK_DNS, GATEWAY_IP } from './ipam.service.js';

export class TopologyService {
  /**
   * Generates dynamic mesh topology for a target peer.
   */
  static async getTopologyForPeer(targetPeer: Peer): Promise<DynamicTopology> {
    const allPeers = await peerStore.getAll();

    // Filter peers excluding the requesting peer and offline nodes
    const otherPeers = allPeers.filter((p) => p.id !== targetPeer.id);

    const meshPeers: PeerMeshEntry[] = otherPeers.map((peer) => {
      // Determine AllowedIPs based on peer role
      let allowedIps = [`${peer.internalIp}/32`];

      // Gateways advertise the entire overlay network CIDR
      if (peer.role === 'gateway') {
        allowedIps = [NETWORK_CIDR];
      }

      return {
        id: peer.id,
        name: peer.name,
        publicKey: peer.publicKey,
        endpoint: peer.endpoint,
        allowedIps,
        persistentKeepalive: 25, // Standard keepalive for NAT traversal
      };
    });

    return {
      peer: {
        id: targetPeer.id,
        name: targetPeer.name,
        internalIp: targetPeer.internalIp,
        listenPort: targetPeer.listenPort,
        allowedIps: [`${targetPeer.internalIp}/32`],
      },
      network: {
        cidr: NETWORK_CIDR,
        dns: NETWORK_DNS,
        gatewayIp: GATEWAY_IP,
      },
      meshPeers,
      generatedAt: new Date().toISOString(),
    };
  }

  /**
   * Generates standard WireGuard configuration file format (wg0.conf) for a peer.
   */
  static generateWireguardConfig(
    targetPeer: Peer,
    privateKeyPlaceholder: string = '<YOUR_PRIVATE_KEY>',
    topology: DynamicTopology
  ): string {
    let conf = `# ==============================================================================
# WireGuard Interface Configuration: wg0
# Node: ${targetPeer.name} (${targetPeer.internalIp})
# Generated by ZTNA Control Plane at ${topology.generatedAt}
# ==============================================================================

[Interface]
PrivateKey = ${privateKeyPlaceholder}
Address = ${targetPeer.internalIp}/16
ListenPort = ${targetPeer.listenPort}
DNS = ${topology.network.dns.join(', ')}

`;

    for (const meshPeer of topology.meshPeers) {
      conf += `# Peer: ${meshPeer.name} (${meshPeer.id})
[Peer]
PublicKey = ${meshPeer.publicKey}
AllowedIPs = ${meshPeer.allowedIps.join(', ')}
`;
      if (meshPeer.endpoint) {
        conf += `Endpoint = ${meshPeer.endpoint}\n`;
      }
      conf += `PersistentKeepalive = ${meshPeer.persistentKeepalive}\n\n`;
    }

    return conf;
  }
}
